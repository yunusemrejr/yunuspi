import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

test('desktop source receipts prevent silent local GUI loss and support a pre-desktop upgrade', t => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-install-'));
  t.after(() => fs.rmSync(temporary, { recursive: true, force: true }));
  const repo = path.join(temporary, 'source'), target = path.join(temporary, 'agent');
  for (const directory of ['scripts/lib', 'core/coding-agent/src', 'agent/extensions', 'agent/npm', 'agent/scripts/lib', 'config', 'desktop']) fs.mkdirSync(path.join(repo, directory), { recursive: true });
  for (const file of ['scripts/install.mjs', 'scripts/build-core.mjs', 'scripts/setup-desktop.mjs', 'agent/scripts/lib/active-core-processes.mjs']) fs.copyFileSync(path.resolve(import.meta.dirname, '..', file), path.join(repo, file));
  for (const name of ['package.json', 'package-lock.json']) fs.writeFileSync(path.join(repo, name), '{}');
  for (const name of ['settings', 'models']) fs.writeFileSync(path.join(repo, `config/${name}.example.json`), '{}');
  fs.writeFileSync(path.join(repo, 'core/coding-agent/package.json'), JSON.stringify({ name: '@yunuspi/coding-agent', version: '0.1.0' }));
  fs.writeFileSync(path.join(repo, 'core/coding-agent/src/cli.js'), 'console.log("fixture");');
  fs.writeFileSync(path.join(repo, 'agent/extensions/manifest.json'), '{}');
  fs.writeFileSync(path.join(repo, 'agent/npm/package.json'), '{}');
  fs.writeFileSync(path.join(repo, 'agent/public.txt'), 'public fixture');
  fs.writeFileSync(path.join(repo, 'desktop/main.mjs'), 'export const fixture = 1;');
  const run = (...flags) => spawnSync(process.execPath, [path.join(repo, 'scripts/install.mjs'), '--target', target, '--apply', '--skip-needle', '--skip-local-lm', ...flags], { encoding: 'utf8' });
  const initial = run(); assert.equal(initial.status, 0, initial.stderr);
  const receiptPath = path.join(target, 'installation.json'), read = () => JSON.parse(fs.readFileSync(receiptPath, 'utf8'));
  assert.equal(read().managedDesktopFiles['main.mjs'], createHash('sha256').update('export const fixture = 1;').digest('hex'));
  fs.writeFileSync(path.join(target, 'settings.json'), '{"fixture":"private-example-state"}');
  const installed = path.join(target, 'runtime/desktop/main.mjs');
  fs.writeFileSync(installed, 'local GUI change');
  const conflict = run('--backup-existing', '--preserve-state');
  assert.notEqual(conflict.status, 0); assert.match(conflict.stderr, /Local desktop source conflicts/);
  assert.equal(fs.readFileSync(installed, 'utf8'), 'local GUI change');
  fs.writeFileSync(installed, 'export const fixture = 1;');
  fs.writeFileSync(path.join(repo, 'desktop/main.mjs'), 'export const fixture = 2;');
  const upgrade = run('--backup-existing', '--preserve-state');
  assert.equal(upgrade.status, 0, upgrade.stderr);
  assert.equal(fs.readFileSync(installed, 'utf8'), 'export const fixture = 2;');
  assert.match(fs.readFileSync(path.join(target, 'settings.json'), 'utf8'), /private-example-state/);
  fs.rmSync(path.join(target, 'runtime/desktop'), { recursive: true });
  const previous = read(); delete previous.managedDesktopFiles; fs.writeFileSync(receiptPath, JSON.stringify(previous));
  assert.equal(run('--backup-existing', '--preserve-state').status, 0, 'pre-desktop installations can upgrade');
});
